export const getCurrentLanguage = (): SupportedLanguage => {
    try {
        const saved = localStorage.getItem('catchos_selected_lang');
        if (saved && (saved in TRANSLATIONS)) {
            return saved as SupportedLanguage;
        }
        // Support prefix matching like 'zh' -> 'zh-CN'
        if (saved && saved.startsWith('zh')) return 'zh-CN';
    } catch {}
    return 'ko';
};

export const setAppLanguage = (code: string) => {
    try {
        localStorage.setItem('catchos_selected_lang', code);
    } catch {}
    if (typeof window !== 'undefined') {
        window.dispatchEvent(new CustomEvent('catchos-language-changed', { detail: { lang: code } }));
    }
};

export const t = (key: string, fallback?: string): string => {
    const lang = getCurrentLanguage();
    const dict = TRANSLATIONS[lang] || TRANSLATIONS.ko;
    if (dict[key]) return dict[key];
    if (TRANSLATIONS.ko[key]) return TRANSLATIONS.ko[key];
    if (TRANSLATIONS.en[key]) return TRANSLATIONS.en[key];
    return fallback || key;
};
